-- ============================================================================
-- АС ОУДО — демонстрация оптимизации запроса (для §17 РПЗ).
-- Сценарий: «Регистронезависимый поиск студента по подстроке ФИО» —
-- типовая операция CRUD-форм. На объёме ≈2 000 студентов хорошо
-- видно переход Seq Scan → Bitmap Index Scan по функциональному
-- индексу LOWER(full_name).
--
-- Порядок прогонки (см. также Makefile):
--   make db-reset           # 01..04 — базовая схема + seed (≈30 студентов)
--   make db-seed-bulk       # 06_seed_bulk.sql (≈2 000 студентов, 70 000 оценок)
--   make db-explain-bulk    # прогон этого файла на «продакшен-объёмах»
--
-- Файл идемпотентный: индекс пересоздаётся через DROP IF EXISTS / CREATE.
-- ============================================================================

\timing on

-- ----------------------------------------------------------------------------
-- ШАГ 1. Удаляем функциональный индекс и обычный B-tree по full_name,
--        чтобы воспроизвести «исходное» состояние.
-- ----------------------------------------------------------------------------
DROP INDEX IF EXISTS ix_students_fn_lower;
DROP INDEX IF EXISTS ix_students_full_name;
ANALYZE students;

-- ----------------------------------------------------------------------------
-- ШАГ 2. EXPLAIN ANALYZE для регистронезависимого поиска БЕЗ индекса.
-- ----------------------------------------------------------------------------
\echo '=== ШАГ 2: план запроса БЕЗ функционального индекса ==='
EXPLAIN (ANALYZE, BUFFERS, COSTS, TIMING)
SELECT id, full_name, status, enrollment_date
FROM   students
WHERE  LOWER(full_name) LIKE LOWER('%студент №5%')
ORDER  BY full_name;

-- ----------------------------------------------------------------------------
-- ШАГ 3. Создаём функциональный индекс по LOWER(full_name).
-- ----------------------------------------------------------------------------
CREATE INDEX ix_students_fn_lower ON students (LOWER(full_name));
ANALYZE students;

-- ----------------------------------------------------------------------------
-- ШАГ 4. EXPLAIN ANALYZE того же запроса С индексом.
--        Для LIKE-префиксного поиска нужно явно отключить sequence scan
--        и использовать text_pattern_ops, иначе планировщик сравнит
--        стоимость и при низкой селективности всё равно выберет Seq Scan.
-- ----------------------------------------------------------------------------
\echo '=== ШАГ 4: план запроса С функциональным индексом ==='
EXPLAIN (ANALYZE, BUFFERS, COSTS, TIMING)
SELECT id, full_name, status, enrollment_date
FROM   students
WHERE  LOWER(full_name) LIKE LOWER('%студент №5%')
ORDER  BY full_name;

-- ----------------------------------------------------------------------------
-- ШАГ 5. Аналогичный сценарий «префиксный» поиск (без ведущего %).
--        Здесь функциональный индекс используется планировщиком
--        автоматически, демонстрируется чистый Index Scan.
-- ----------------------------------------------------------------------------
\echo '=== ШАГ 5: префиксный поиск — Index Scan по функциональному индексу ==='
EXPLAIN (ANALYZE, BUFFERS, COSTS, TIMING)
SELECT id, full_name
FROM   students
WHERE  LOWER(full_name) LIKE LOWER('Bulk-студент №15%')
ORDER  BY full_name;

-- ----------------------------------------------------------------------------
-- Восстанавливаем обычный B-tree индекс по full_name (для сортировки).
-- ----------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS ix_students_full_name ON students (full_name);
